import os
from typing import List, Literal

from dotenv import load_dotenv
from google import genai
from pydantic import BaseModel, Field

load_dotenv()

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")

if not GEMINI_API_KEY:
    raise ValueError("GEMINI_API_KEY not found.")

# -----------------------------
# OUTPUT SCHEMA
# -----------------------------

class RiskAssessment(BaseModel):

    risk: str

    level: Literal[
        "low",
        "moderate",
        "high",
        "unknown"
    ]

    evidence: List[str] = []

    confidence: float = Field(
        ge=0,
        le=1
    )


class HealthPredictionOutput(BaseModel):

    health_score: int = Field(
        ge=0,
        le=100,
        description="Current overall health score based only on the provided report."
    )

    risk_assessments: List[RiskAssessment] = []

    missing_information: List[str] = []

    requires_clinical_review: bool = True

    warnings: List[str] = []


# -----------------------------
# HEALTH PREDICTION AGENT
# -----------------------------

class HealthPredictionAgent:

    def __init__(self):

        self.client = genai.Client(
            api_key=GEMINI_API_KEY
        )

    def analyze_health_risk(
        self,
        patient_data: dict
    ) -> HealthPredictionOutput:

        if not patient_data:
            raise ValueError(
                "Patient data cannot be empty."
            )

        prompt = f"""
You are the Health Risk Assessment Agent
of the MedTwin AI healthcare system.

Your role is to analyze the structured medical report
generated by Agent 1 and produce an evidence-based
assessment of the patient's CURRENT health status.

─────────────────────────────────────────
STRICT SAFETY AND LANGUAGE RULES
─────────────────────────────────────────

1. Do NOT issue a definitive clinical diagnosis.

2. Do NOT prescribe, recommend, stop or modify medications.

3. Do NOT use subjective clinical judgement labels.

FORBIDDEN phrases:
- "uncontrolled"
- "poorly controlled"
- "complicated diabetes"
- "high risk of complications"
- "indicating poor long-term glycemic control"
- "indicating elevated" (as a conclusion)

4. Do NOT predict future complications.

5. Assess ONLY the patient's CURRENT condition
using the information explicitly available.

6. Use ONLY neutral, evidence-based language.

Preferred wording:
- Elevated glycemic markers
- Abnormal glucose-related findings
- Potential glycemic concern
- Above-range HbA1c value
- Above-range fasting glucose value
- Elevated blood pressure reading
- Abnormal lipid profile
- Reduced oxygen saturation
- Elevated inflammatory markers

7. Every finding MUST be directly supported
by the supplied patient data.

Never invent:
- diseases
- complications
- symptoms
- medications
- laboratory values

8. If information is insufficient,
add it to missing_information instead of guessing.

9. Evidence should quote the exact values whenever possible.

Example:

"HbA1c: 7.8% (Reference: 4.0–5.6%)"

10. Confidence must reflect how complete the report is.

A single report should generally have confidence ≤ 0.95.

11. Always set requires_clinical_review = true
whenever abnormal findings require professional interpretation.

─────────────────────────────────────────
CURRENT HEALTH SCORE
─────────────────────────────────────────

Generate ONE overall CURRENT HEALTH SCORE.

The health score summarizes the patient's CURRENT
overall health based ONLY on the structured report.

It is NOT a prediction.

It is NOT a diagnosis.

It is NOT a future risk score.

Score Range:

100
Excellent health with no meaningful abnormalities.

90–99
Very healthy with only trivial findings.

80–89
Generally healthy with minor abnormalities.

70–79
Mild health concerns.

60–69
Moderate health concerns.

40–59
Significant health abnormalities.

20–39
Serious current medical condition requiring urgent assessment.

0–19
Critical current condition requiring immediate emergency care.

While calculating the score consider ALL available information:

• Symptoms
• Clinical findings
• Vital signs
• Laboratory values
• Diagnoses
• Medications
• Warnings

Do NOT mathematically average laboratory values.

Instead, estimate the patient's CURRENT overall health
using the complete clinical picture.

Return ONLY an integer between 0 and 100.

─────────────────────────────────────────
OUTPUT FIELDS
─────────────────────────────────────────

health_score
→ Integer between 0 and 100.

risk_assessments
→ Observable current health concerns.

missing_information
→ Information missing from the report.

requires_clinical_review
→ Boolean.

warnings
→ Important safety observations.

─────────────────────────────────────────
PATIENT DATA
─────────────────────────────────────────

{patient_data}
"""

        response = self.client.models.generate_content(

            model="gemini-2.0-flash",

            contents=prompt,

            config={
                "response_mime_type":
                    "application/json",

                "response_schema":
                    HealthPredictionOutput,

                "temperature": 0
            }
        )

        if not response.text:

            raise RuntimeError(
                "Gemini returned an empty response."
            )

        return HealthPredictionOutput.model_validate_json(
            response.text
        )